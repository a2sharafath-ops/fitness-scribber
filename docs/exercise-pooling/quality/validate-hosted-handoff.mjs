// Read-only report consistency; this does not rerun hosted application tests.
import assert from 'node:assert/strict'
import { readFileSync, existsSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
const pack = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const json = path => JSON.parse(readFileSync(resolve(pack, path), 'utf8'))
const report = json('quality/hosted-build-verification.json')
const matrix = json('quality/hosted-acceptance-matrix.json')
const backlog = json('sprint-backlog.json')
assert.equal(backlog.tasks.length, 82)
assert.equal(new Set(backlog.tasks.map(t => t.id)).size, 82)
assert.equal(matrix.cases.length, 110)
assert.equal(new Set(matrix.cases.map(c => c.id)).size, 110)
for (const [status, count] of Object.entries(matrix.counts)) assert.equal(matrix.cases.filter(c => c.status === status).length, count)
assert.equal(matrix.acceptanceComplete, false)
assert.equal(matrix.productionReady, false)
assert.equal(report.acceptance.complete, false)
assert.equal(report.unit.tests, 132)
assert.equal(report.unit.passed, report.unit.tests)
assert.equal(report.unit.failed, 0)
assert.equal(report.hosted.failedChecks, 0)
assert.equal(report.hosted.uniquePassingCheckNames + report.hosted.repeatedEntries, report.hosted.apiCheckEntries)
assert.equal(report.testedApplicationCommit, backlog.hostedVerificationSummary.testedCodeCommit)
assert.equal(report.backend.migrations, 18)
assert.equal(report.backend.functions, 6)
assert.equal(report.backend.jwtVerification, true)
assert.equal(report.containment.testUsersDisabled, report.containment.testUsersCreated)
assert.equal(report.containment.testUsersCreated, 5)
for (const flag of Object.values(report.backend.flags)) assert.equal(flag, false)
for (const flag of Object.values(report.preview.browserFlags)) assert.equal(flag, false)
for (const gate of Object.values(report.release)) assert.equal(gate, false)
assert.equal(report.preservation.baselineRows, 549)
assert.equal(report.preservation.baselineTables, 52)
assert.deepEqual(report.preservation.missingOrChangedBaselineTables, [])
assert.equal(report.preservation.baselinePreserved, true)
assert.equal(report.preservation.storageObjects, 0)
assert.equal(report.recovery.offDevice, false)
assert.equal(report.recovery.fullManagedServiceRestore, false)
assert(report.preview.verifiedBuildsThroughCandidate + report.preview.reservedDocumentationDeliveryBuilds <= report.preview.approvedBuildLimit)
for (const task of backlog.tasks) for (const file of task.hostedEvidence || []) assert(existsSync(resolve(pack, file)), file)
assert.equal(backlog.productionChangesAuthorized, false)
assert.equal(backlog.hostedTestProposal.mainPromotionAuthorized, false)
for (const id of ['FP-601', 'FP-602', 'FP-603', 'FP-604', 'FP-607', 'FP-608', 'FP-702', 'FP-705', 'FP-802', 'FP-805']) assert.notEqual(backlog.tasks.find(t => t.id === id).status, 'done')
console.log(JSON.stringify({ status: 'passed-hosted-evidence-consistency', tasks: 82, specifications: 110, applicationTestsExecuted: false, releaseAccepted: false }))
