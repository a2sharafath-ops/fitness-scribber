// Mechanically render explicit, reviewable replacements; retain the original
// 18 migration files/checksums. Run before rehearsing this additive migration.
import {readFileSync,writeFileSync} from 'node:fs'
import assert from 'node:assert/strict'
import {schemas} from './hosted-migration-plan.mjs'
const functions=new Map()
for(const file of schemas){
 const sql=readFileSync('supabase/'+file,'utf8')
 for(const match of sql.matchAll(/create or replace function public\.(\w+)\([\s\S]*?\$\$[\s\S]*?\$\$;/g))functions.set(match[1],match[0])
}
const output=[],names=[]
for(const [name,original] of functions){
 if(name==='pooling_enabled')continue
 let next=original
 const client=name==='pooling_execution'?'a.client_id':'target_client'
 next=next.replaceAll('(select r1 from public.pooling_runtime where singleton)',`public.pooling_module_enabled(${client},'r1')`)
 next=next.replaceAll('(select r1 and r3 from public.pooling_runtime where singleton)',`public.pooling_module_enabled(${client},'r3')`)
 next=next.replaceAll("exists(select 1 from public.pooling_runtime where singleton and r1 and case when proposal->>'kind'='daily' then r2 else r3 end)","public.pooling_module_enabled(target_client,case when proposal->>'kind'='daily' then 'r2' else 'r3' end)")
 next=next.replaceAll("exists(select 1 from public.pooling_runtime where singleton and r1 and case when r.kind='daily' then r2 else r3 end)","public.pooling_module_enabled(target_client,case when r.kind='daily' then 'r2' else 'r3' end)")
 if(name==='pooling_guard_legacy_write'){
  next=next.replace("if actor is null or not public.pooling_enabled() then",'if actor is null then')
  next=next.replace("cid:=coalesce(after_row->>'clientId',before_row->>'clientId');", "cid:=coalesce(after_row->>'clientId',before_row->>'clientId');\n if not public.pooling_governed_client(cid) then if TG_OP='DELETE' then return old;else return new;end if;end if;")
 }
 if(name==='pooling_athlete_snapshot'){
  next=next.replace(" if not public.pooling_enabled() then raise exception 'feature_disabled'; end if;\n",'')
  next=next.replace("if not found then return '{\"client\":null}'; end if;","if not found then return '{\"client\":null}'; end if;\n if not public.pooling_governed_client(c.id) then raise exception 'feature_disabled';end if;")
 }
 if(name==='pooling_client_home')next=next.replace('not public.pooling_enabled()','not public.pooling_governed_client(target_client)')
 if(name==='pooling_review_workspace')next=next.replace("where m.state='published'","where m.state='published' and public.pooling_manifest_allowed(target_client,m.id)")
 if(['pooling_decision_input','pooling_source_bundle','pooling_week_input'].includes(name)){
  const marker="select * into m from public.pooling_manifests where id="
  assert(next.includes(marker),name)
  const lookup=/select \* into m from public\.pooling_manifests where id=[^;]+;/
  next=next.replace(lookup,match=>match+"\n if not public.pooling_manifest_allowed(target_client,m.id) then raise exception 'test_scope_mismatch';end if;")
 }
 if(next!==original){assert(!next.includes('from public.pooling_runtime'),name);names.push(name);output.push(next)}
}
assert(names.includes('pooling_execution')&&names.includes('pooling_save_draft')&&names.includes('pooling_approve'))
let legacy=readFileSync('supabase/schema_pooling_legacy_boundary.sql','utf8')
legacy=legacy.slice(legacy.indexOf('drop policy if exists athlete_reads_self'),legacy.indexOf('-- Direct client writes'))
legacy=legacy.replace('not public.pooling_enabled());','not public.pooling_governed_client(id));')
legacy=legacy.replaceAll('not public.pooling_enabled()', 'not public.pooling_governed_client("clientId")')
const base=readFileSync('supabase/pooling_coach_test_base.sql','utf8')
const sql='-- Generated by scripts/pooling/build-coach-test-migration.mjs. A31 only.\nbegin;\n'+base+'\n'+legacy+'\n'+output.join('\n\n')+"\nnotify pgrst,'reload schema';\ncommit;\n"
writeFileSync('supabase/schema_pooling_coach_test.sql',sql)
console.log(JSON.stringify({functions:names,count:names.length}))
